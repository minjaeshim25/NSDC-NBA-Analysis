import pandas as pd
import os

# 1. Clear text display boundaries completely
pd.set_option('display.max_columns', None)
pd.set_option('display.max_rows', None)
pd.set_option('display.width', 1000)

# 2. Extract filenames safely
all_files = os.listdir('.')
file_0304 = [f for f in all_files if '2003' in f and f.endswith('.csv')][0]
file_0405 = [f for f in all_files if ('2004-2005' in f or '2005' in f) and '2003' not in f and f.endswith('.csv')][0]

print(f"✅ Processing 2003-04 Baseline: '{file_0304}'")
print(f"✅ Processing 2004-05 Comparison: '{file_0405}'")

# 3. Read raw sheets entirely to pull correct columns
df_raw_04 = pd.read_csv(file_0304)
df_raw_05 = pd.read_csv(file_0405, header=1)
df_raw_05 = df_raw_05.iloc[1:].copy() # Drops the leftover string text layer safely

# 4. Standardize column names based on their positions
spatial_zones = ['Restricted_Area', 'In_The_Paint_Non_RA', 'Mid_Range',
                 'Left_Corner_3', 'Right_Corner_3', 'Corner_3', 'Above_The_Break_3']

def map_spatial_headers(df):
    df.columns = [str(c).strip() for c in df.columns]
    new_headers = []
    metric_counter = 0
    zone_index = 0

    # Use explicit positional indices to bypass word match bugs
    for idx, col in enumerate(df.columns):
        if idx == 0:
            new_headers.append('Player_Clean')
        elif 1 <= idx <= 4: # Maps Team, Age, Mins, GP columns safely by index positions
            new_headers.append(f"{col}_meta")
        elif metric_counter < len(spatial_zones) * 3:
            zone_name = spatial_zones[zone_index]
            sub_metric = 'FGM' if metric_counter % 3 == 0 else ('FGA' if metric_counter % 3 == 1 else 'FG%')
            new_headers.append(f"{zone_name}_{sub_metric}")
            metric_counter += 1
            if metric_counter % 3 == 0:
                zone_index += 1
        else:
            new_headers.append(col)
    df.columns = new_headers
    return df

# Apply column mappings to both eras
df_mid_04 = map_spatial_headers(df_raw_04)
df_mid_05 = map_spatial_headers(df_raw_05)

# Force names to strip trailing spaces
df_mid_04['Player_Clean'] = df_mid_04['Player_Clean'].astype(str).str.strip()
df_mid_05['Player_Clean'] = df_mid_05['Player_Clean'].astype(str).str.strip()

